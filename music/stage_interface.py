"""Stage the reviewed original bank and emit exact controller PCM for C++."""
from pathlib import Path
import json,shutil,wave
import numpy as np
ROOT=Path(__file__).resolve().parents[1]; P=ROOT/'build/research/interface-audio-original-20261031'
destination=ROOT/'assets/audio/museum-navigation/glass';backup=P/'previous-bank'
if not backup.exists():shutil.copytree(destination,backup)
for f in (P/'bank/glass').glob('*.wav'):shutil.copy2(f,destination/f.name)
(destination/'index.txt').write_text('\n'.join(sorted(f.name for f in destination.glob('*.wav')))+'\n',encoding='ascii')
header=['// Original Pixel Museum PCM. Generated by compose_interface.py and emit_native.py.',
 '// No recordings or third-party sound assets. SPDX-License-Identifier: GPL-3.0-or-later',
 '#pragma once','#include "audio/controller_feedback.hpp"','#include <algorithm>','#include <cstdint>',
 'namespace hui::audio::museum_original {','struct Gesture {const std::int16_t* samples=nullptr;unsigned frames=0;};']
cues=['ui_focus','ui_confirm','ui_back','timeline_culture','timeline_games','invader_shot']
for cue in cues:
 with wave.open(str(P/'controller'/(cue+'.wav')),'rb')as w:
  assert w.getnchannels()==1 and w.getframerate()==48000 and w.getsampwidth()==2
  samples=np.frombuffer(w.readframes(w.getnframes()),'<i2')
 header.append('inline constexpr std::int16_t '+cue+'[]={')
 header.extend(','.join(str(int(v))for v in samples[i:i+32])+','for i in range(0,len(samples),32));header.append('};')
header+=['inline Gesture gesture(SpeakerCue cue){switch(cue){']
for cue in cues:header.append('case SpeakerCue::'+cue+':return{'+cue+',unsigned(sizeof('+cue+')/sizeof('+cue+'[0]))};')
header+=['default:return{};}}',
 'inline float read(Gesture g,unsigned position,float pitch){',
 'if(!g.samples||g.frames<2)return 0.f;',
 'const float at=float(position)*pitch;if(at<0||at>=float(g.frames-1))return 0.f;',
 'const unsigned i=unsigned(at);const float a=at-float(i);return (float(g.samples[i])*(1-a)+float(g.samples[i+1])*a)/32768.f;',
 '}','}']
out=ROOT/'src/audio/museum_interface_pcm.hpp';out.write_text('\n'.join(header)+'\n',encoding='ascii')
manifest=json.loads((P/'manifest.json').read_text(encoding='utf8'))
manifest['staged_bank']='assets/audio/museum-navigation/glass';manifest['unchanged_legacy_file']='restart_01.wav';manifest['native_controller_header']='src/audio/museum_interface_pcm.hpp'
(P/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
measurements={'sample_rate':48000,'channels':2,'bits':16,'source':'music/compose_interface.py','interface_cue_count':20,'loaded_wav_count':len(list(destination.glob('*.wav'))),'unchanged_legacy_restart':True,'recommended_ui_bus_gain':.18,'soundbank_pitch_jitter':0,'loudness_method':manifest['loudness_method'],'clips':[dict(r,file=Path(r['file']).name)for r in manifest['ui_clips']],'total_wav_bytes':sum(f.stat().st_size for f in destination.glob('*.wav'))}
(ROOT/'music/navigation-measurements.json').write_text(json.dumps(measurements,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
print('Staged',len(list(destination.glob('*.wav'))),'WAVs; preserved restart; embedded',len(cues),'controller gestures')
