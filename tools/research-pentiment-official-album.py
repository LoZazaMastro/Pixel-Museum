"""Bounded exact official-album metadata checks; no audio downloads."""
import importlib.util,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
F=ROOT/'build/research/soundtrack-broad/modern-next-four'
def module(name,path):
 s=importlib.util.spec_from_file_location(name,ROOT/path);m=importlib.util.module_from_spec(s);s.loader.exec_module(m);return m
music=module('pentiment_music','content/expansion/soundtrack-broad-pipeline.py')
video=module('pentiment_video','tools/discover-museum-videos.py')
flat=json.loads((F/'pentiment-official-album-flat.json').read_text(encoding='utf8'))
records=[];failures=0
for row in flat['entries']:
 r={'youtube_id':row['id'],'playlist_title':row['title']}
 try:
  meta=video.metadata(row['id'],row)
  w=music.watch(row['id'])
  assert w['title']==meta['title'] and float(w['lengthSeconds'])==float(meta['duration'])
  assert w['channelId']==meta['channel_id']
  desc=w['shortDescription']
  assert 'Provided to YouTube by Virgin Music Group' in desc and 'Microsoft Studios Music' in desc and 'Pentiment' in desc
  assert 'Auto-generated by YouTube' in desc
  assert meta['native_compatible_avc_aac']
  r.update(status='verified_pending_peer',metadata=meta,provided_label_description=desc)
  failures=0
 except Exception as err:
  r.update(status='held',reason=str(err));failures+=1
 records.append(r)
 (F/'pentiment-official-album-native-research.json').write_text(json.dumps({'records':records,'audio_downloaded':False},ensure_ascii=False,indent=2)+'\n',encoding='utf8')
 print(r['status'],r['playlist_title'],flush=True)
 if failures>=3:break
