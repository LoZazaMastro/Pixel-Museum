"""Freeze the public label-delivered album without downloading audio."""
import hashlib
import json
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / 'build/research/soundtrack-broad/modern-next-four'
load = lambda p: json.loads(p.read_text(encoding='utf8'))
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
flat_path = FOLDER / 'pentiment-official-album-flat.json'
research_path = FOLDER / 'pentiment-official-album-native-research.json'
flat, research = load(flat_path), load(research_path)
assert flat['id'] == 'OLAK5uy_lGMrRRANy5JrlvVYyEmqYGkp5JrWjUJfo'
assert len(flat['entries']) == len(research['records']) == 37
primary = 'https://www.alkemie.org/pentiment-album'
publisher = 'https://news.xbox.com/en-us/2022/12/27/pentiment-soundtrack-vinyl/'
primary_path = FOLDER / 'pentiment-alkemie-official-album.html'
assert 'Alkemie curated, composed, and arranged' in html.unescape(re.sub('<[^>]+>', '', primary_path.read_text(encoding='utf8')))
tracks, receipts = [], []
for index, (row, checked) in enumerate(zip(flat['entries'], research['records']), 1):
    identifier = row['id']
    assert checked['status'] == 'verified_pending_peer' and identifier == checked['youtube_id']
    watch_path = ROOT / 'build/research/soundtrack-broad/watch' / (identifier + '.json')
    native_path = ROOT / 'build/research/video-discovery' / ('video-' + identifier + '.json')
    watch, native = load(watch_path), load(native_path)
    assert watch['title'] == native['title'] == row['title']
    assert float(watch['lengthSeconds']) == native['duration']
    assert watch['channelId'] == native['channel_id']
    assert native['native_compatible_avc_aac'] is True
    description = watch['shortDescription']
    assert 'Provided to YouTube by Virgin Music Group' in description
    assert 'Microsoft Studios Music' in description and 'Auto-generated by YouTube' in description
    artist = 'Lingua Ignota' if index == 37 else 'Alkemie'
    channel = 'UCmWL8nQYdv0MMRlNMQ8NJJA' if index == 37 else 'UCD1E5ftOh4dLgLAvq0Slmjw'
    assert watch['channelId'] == channel and (' · ' + artist) in description
    tracks.append({
        'youtube_id': identifier, 'url': 'https://www.youtube.com/watch?v=' + identifier,
        'title': watch['title'], 'creator': artist,
        'source_page': 'https://www.youtube.com/watch?v=' + identifier,
        'channel_url': 'https://www.youtube.com/channel/' + channel,
        'uploader': watch['author'], 'duration_seconds': int(native['duration']),
        'recording_album': 'Pentiment (Original Soundtrack)', 'original_game_year': 2022,
        'recording_album_release_year': 2022, 'published_album_track_number': index,
        'publishing_kind': 'official_label_delivery', 'official_uploader_verified': True,
        'composer_source': publisher if index == 37 else primary,
        'artist_credit_scope': ('Lingua Ignota composed and performed Ein Traum, as credited by the publisher.' if index == 37 else
            'Alkemie is the credited recording ensemble. Its work includes original compositions and arrangements of historical music; this is not an exclusive underlying-composer attribution.'),
        'rights': 'Microsoft Studios Music, Obsidian Entertainment and the respective composers, arrangers and performers retain their rights.',
        'publication_metadata_receipt': watch_path.relative_to(ROOT).as_posix(),
        'native_codec_metadata_receipt': native_path.relative_to(ROOT).as_posix(),
        'native_codec_metadata_verified': True, 'playback_verified_on_ps5': False,
    })
    for path in (watch_path, native_path):
        receipts.append({'path': path.relative_to(ROOT).as_posix(), 'sha256': sha(path)})
for path in (flat_path, research_path, primary_path):
    receipts.append({'path': path.relative_to(ROOT).as_posix(), 'sha256': sha(path)})
candidate = {
    'schema_version': 1, 'publication_status': 'candidate_pending_independent_peer',
    'entries': [{
        'entry_id': 'daily-04-23', 'match_title': 'Pentiment', 'match_year': 2022,
        'title': 'Listen to Pentiment', 'composer': 'Alkemie and Lingua Ignota',
        'curator_note': 'Listen to the music of Alkemie and Lingua Ignota from Pentiment.',
        'replace_existing_tracks': True, 'full_album_collection': True,
        'coverage_status': 'OFFICIAL_LABEL_DELIVERED_37_TRACK_ALBUM',
        'album_completeness': {'published_title_inventory': 37, 'available_tracks': 37,
            'qualification': 'All 37 entries in the actual public label-delivered album, including the short album cue The Parting and the guest recording Ein Traum. No claim to every incidental game audio file.'},
        'tracks': tracks,
    }],
    'publisher_credit_source': publisher,
    'publisher_credit_evidence': 'Xbox Wire, Obsidian Entertainment, 27 December 2022: Alkemie composed original music and adapted historical works; Lingua Ignota composed and performed Ein Traum.',
    'publisher_page_access': 'Read with the web reader; direct HTTP fetch returned 403, so no raw HTML file is claimed.',
    'source_receipts': receipts, 'audio_downloaded': False,
    'source_catalog_or_runtime_changed': False,
}
path = FOLDER / 'pentiment-thirty-seven-official-album-candidate.json'
path.write_text(json.dumps(candidate, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
print(path.relative_to(ROOT), sha(path))
