#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Language {
    En,
    It,
    Fr,
    De,
    Es,
}

impl Language {
    pub const ALL: [Self; 5] = [Self::En, Self::It, Self::Fr, Self::De, Self::Es];
    pub fn code(self) -> &'static str {
        ["en", "it", "fr", "de", "es"][self as usize]
    }
    pub fn native(self) -> &'static str {
        ["English", "Italiano", "Français", "Deutsch", "Español"][self as usize]
    }
    pub fn from_code(code: &str) -> Self {
        Self::ALL
            .into_iter()
            .find(|l| l.code() == code)
            .unwrap_or(Self::En)
    }
    pub fn detect() -> Self {
        let value = std::env::var("LANG")
            .unwrap_or_default()
            .to_ascii_lowercase();
        Self::from_code(value.get(..2).unwrap_or("en"))
    }
    pub fn text(self, key: Text) -> &'static str {
        STRINGS[key as usize][self as usize]
    }
}

